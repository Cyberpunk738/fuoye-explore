const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');

(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1280,height:720},reducedMotion:'reduce'});
  await page.clock.install();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(process.env.BASE_URL||'http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
    await page.locator('.loading').waitFor({state:'detached',timeout:60000});
    await page.waitForFunction(()=>Number(document.querySelector('.fps')?.dataset.renderCount)>0);
    console.log('Explorer ready');
    const count=await page.locator('[data-building]').count();assert.equal(count,85);
    const overview=await page.locator('.fps').evaluate(e=>({...e.dataset}));
    assert.ok(Number(overview.triangles)<250000);
    await page.screenshot({path:'output/fuoye-reference-layout.png',timeout:60000});
    const idleCount=await page.locator('.fps').getAttribute('data-render-count');
    await page.waitForTimeout(600);
    assert.equal(await page.locator('.fps').getAttribute('data-render-count'),idleCount);
    await page.locator('[data-building]').nth(20).click();
    await page.waitForFunction(()=>document.querySelector('.fps')?.dataset.idle==='true');
    assert.equal(await page.locator('[aria-current="true"]').count(),1);
    await page.screenshot({path:'output/fuoye-building-close.png',timeout:60000});
    await page.getByRole('button',{name:'Drive',exact:true}).click();
    await page.getByRole('heading',{name:'Campus Courier',exact:true}).waitFor();
    await page.screenshot({path:'output/fuoye-courier-menu.png',timeout:60000});
    await page.getByRole('button',{name:'Free drive',exact:true}).click();
    const positionBefore=await page.locator('.drive-hud').evaluate(e=>({x:Number(e.dataset.x),z:Number(e.dataset.z)}));
    await page.keyboard.down('w');await page.waitForTimeout(850);await page.keyboard.up('w');
    const positionAfter=await page.locator('.drive-hud').evaluate(e=>({x:Number(e.dataset.x),z:Number(e.dataset.z)}));
    assert.ok(Math.hypot(positionAfter.x-positionBefore.x,positionAfter.z-positionBefore.z)>.05);
    console.log('Free driving verified');
    await page.keyboard.press('r');
    await page.locator('.toast').filter({hasText:'Back on the road'}).waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Drive',exact:true}).click();
    await page.getByRole('button',{name:'Start',exact:true}).click();
    await page.locator('.job').filter({hasText:'Deliver to'}).waitFor();
    assert.equal(await page.locator('.drive-hud').getAttribute('data-state'),'run');
    await page.screenshot({path:'output/fuoye-courier-run.png',timeout:60000});
    await page.clock.fastForward(76000);
    await page.getByRole('heading',{name:"Time's up",exact:true}).waitFor();
    await page.getByRole('button',{name:'Drive again',exact:true}).click();
    assert.equal(await page.locator('.drive-hud').getAttribute('data-state'),'run');
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Walk',exact:true}).click();
    await page.keyboard.down('w');await page.waitForTimeout(500);await page.keyboard.up('w');
    await page.keyboard.press('Space');
    await page.waitForFunction(()=>Number(document.querySelector('.walk-hud')?.dataset.jumpPeak)>0);
    console.log('Walking and jumping verified');
    await page.screenshot({path:'output/fuoye-walk.png',timeout:60000});
    await page.getByRole('button',{name:'Exit walk',exact:true}).click();
    await page.getByRole('button',{name:'Night',exact:true}).click();
    assert.equal(await page.locator('#app').getAttribute('data-night'),'true');
    await page.screenshot({path:'output/fuoye-night.png',timeout:60000});
    await page.getByRole('button',{name:'Day',exact:true}).click();
    await page.getByRole('button',{name:'Full view',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.fps')?.dataset.idle==='true');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'output/fuoye-mobile.png',timeout:60000});
    const bounds=await page.locator('.tools').boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=391);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight>innerHeight),false);
    const mobile=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'reduce'});
    mobile.on('pageerror',e=>errors.push(e.message));
    await mobile.goto(process.env.BASE_URL||'http://127.0.0.1:5173/');
    await mobile.locator('.loading').waitFor({state:'detached',timeout:60000});
    assert.equal(await mobile.locator('.list').evaluate(e=>e.open),false);
    await mobile.getByRole('button',{name:'Walk',exact:true}).click();
    const touch=await mobile.context().newCDPSession(mobile);
    const beforeTouch=await mobile.locator('.walk-hud').evaluate(e=>({x:Number(e.dataset.x),z:Number(e.dataset.z)}));
    await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:80,y:550,id:1}]});
    await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:80,y:510,id:1}]});
    await mobile.waitForTimeout(400);
    const afterTouch=await mobile.locator('.walk-hud').evaluate(e=>({x:Number(e.dataset.x),z:Number(e.dataset.z)}));
    assert.ok(Math.hypot(afterTouch.x-beforeTouch.x,afterTouch.z-beforeTouch.z)>.05);
    await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await mobile.getByRole('button',{name:'Exit walk',exact:true}).click();
    await mobile.screenshot({path:'output/fuoye-mobile.png',timeout:60000});
    await mobile.close();
    const review=await browser.newPage();
    await review.goto(new URL('review.html',process.env.BASE_URL||'http://127.0.0.1:5173/').href);
    await review.waitForFunction(()=>document.querySelector('#visible-count')?.textContent.includes('outlines in view'));
    assert.ok(await review.locator('#map .leaflet-container, #map.leaflet-container').count());
    assert.equal(await review.locator('#map').isVisible(),true);
    assert.equal(await review.locator('#scene').isVisible(),false);
    await review.close();
    assert.deepEqual(errors,[]);
    await fs.writeFile('output/explorer-checks.json',JSON.stringify({directoryCount:count,overview,idleRendersStopped:true,freeDriveMovement:positionAfter,checks:['directory selection','courier menu','free drive','road reset','delivery run','timer expiry','retry','walking','jumping','night/day','full view','mobile layout','touch joystick movement','review map route'],errors},null,2));
    console.log('Explorer checks passed',overview);
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
